CREATE TABLE PAIS (
    id_pais NUMBER(3)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 9 INCREMENT BY 3),
    nom_pais VARCHAR2(30),
    CONSTRAINT PK_PAIS PRIMARY KEY (id_pais)
);

CREATE TABLE CIUDAD (
    id_ciudad NUMBER(3),
    nom_ciudad VARCHAR2(30),
    cod_pais NUMBER(3),
    CONSTRAINT PK_CIUDAD PRIMARY KEY (id_ciudad),
    CONSTRAINT FK_CIUDAD_PAIS FOREIGN KEY (cod_pais)
        REFERENCES PAIS(id_pais)
);

CREATE TABLE SUCURSAL (
    id_sucursal CHAR(3),
    nom_sucursal VARCHAR2(20),
    calle VARCHAR2(20),
    num_calle NUMBER(4),
    cod_ciudad NUMBER(3),
    CONSTRAINT PK_SUCURSAL PRIMARY KEY (id_sucursal),
    CONSTRAINT FK_SUCURSAL_CIUDAD FOREIGN KEY (cod_ciudad)
        REFERENCES CIUDAD(id_ciudad)
);

CREATE TABLE SERVICIO (
    id_servicio NUMBER(3),
    descripcion VARCHAR2(100),
    costo NUMBER(7),
    CONSTRAINT PK_SERVICIO PRIMARY KEY (id_servicio)
);

CREATE TABLE MECANICO (
    cod_mecanico NUMBER(5)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 460 INCREMENT BY 7),
    pnombre VARCHAR2(20),
    snombre VARCHAR2(20),
    apaterno VARCHAR2(20),
    amaterno VARCHAR2(20),
    bono_jefatura NUMBER(10),
    sueldo NUMBER(10),
    monto_impuestos NUMBER(10),
    cod_supervisor NUMBER(5),
    CONSTRAINT PK_MECANICO PRIMARY KEY (cod_mecanico),
    CONSTRAINT FK_MECANICO_SUPERVISOR FOREIGN KEY (cod_supervisor)
        REFERENCES MECANICO(cod_mecanico)
);

CREATE TABLE MARCA (
    id_marca NUMBER(2),
    descripcion VARCHAR2(20),
    CONSTRAINT PK_MARCA PRIMARY KEY (id_marca)
);

CREATE TABLE MODELO (
    id_modelo NUMBER(5),
    marca_id NUMBER(2),
    descripcion VARCHAR2(20),
    CONSTRAINT PK_MODELO PRIMARY KEY (id_modelo),
    CONSTRAINT FK_MODELO_MARCA FOREIGN KEY (marca_id)
        REFERENCES MARCA(id_marca)
);

CREATE TABLE TIPO_AUTOMOVIL (
    id_tipo CHAR(3),
    descripcion VARCHAR2(20),
    CONSTRAINT PK_TIPO_AUTOMOVIL PRIMARY KEY (id_tipo)
);

CREATE TABLE CLIENTE (
    cl_rut NUMBER(8),
    dv CHAR(1),
    pnombre VARCHAR2(20),
    snombre VARCHAR2(20),
    apaterno VARCHAR2(20),
    amaterno VARCHAR2(20),
    telefono VARCHAR2(12),
    email VARCHAR2(40),
    tipo_cliente CHAR(1),
    CONSTRAINT PK_CLIENTE PRIMARY KEY (cl_rut)
);

CREATE TABLE ESTANDAR (
    cl_rut NUMBER(8),
    puntaje_fidelidad NUMBER(10),
    CONSTRAINT PK_ESTANDAR PRIMARY KEY (cl_rut),
    CONSTRAINT FK_ESTANDAR_CLIENTE FOREIGN KEY (cl_rut)
        REFERENCES CLIENTE(cl_rut)
);

CREATE TABLE PREMIUM (
    cl_rut NUMBER(8),
    pesos_clientes NUMBER(10),
    monto_credito NUMBER(10),
    CONSTRAINT PK_PREMIUM PRIMARY KEY (cl_rut),
    CONSTRAINT FK_PREMIUM_CLIENTE FOREIGN KEY (cl_rut)
        REFERENCES CLIENTE(cl_rut)
);

CREATE TABLE AUTOMOVIL (
    patente CHAR(8),
    anio NUMBER(4),
    cant_puertas NUMBER(1),
    km NUMBER(6),
    color_tipo VARCHAR2(30),
    cod_tipo CHAR(3),
    cod_modelo NUMBER(5),
    cod_marca NUMBER(2),
    cl_rut NUMBER(8),
    CONSTRAINT PK_AUTOMOVIL PRIMARY KEY (patente),
    CONSTRAINT FK_AUTOMOVIL_TIPO FOREIGN KEY (cod_tipo)
        REFERENCES TIPO_AUTOMOVIL(id_tipo),
    CONSTRAINT FK_AUTOMOVIL_MODELO FOREIGN KEY (cod_modelo)
        REFERENCES MODELO(id_modelo),
    CONSTRAINT FK_AUTOMOVIL_MARCA FOREIGN KEY (cod_marca)
        REFERENCES MARCA(id_marca),
    CONSTRAINT FK_AUTOMOVIL_CLIENTE FOREIGN KEY (cl_rut)
        REFERENCES CLIENTE(cl_rut)
);

CREATE TABLE MANTENCION (
    num_mantencion NUMBER(4),
    cod_sucursal CHAR(3),
    cod_mecanico NUMBER(5),
    patente CHAR(8),
    fecha_ingreso DATE,
    fecha_salida DATE,
    costo_total NUMBER(7),
    estado VARCHAR2(15),
    CONSTRAINT PK_MANTENCION PRIMARY KEY (num_mantencion),
    CONSTRAINT FK_MANTENCION_SUCURSAL FOREIGN KEY (cod_sucursal)
        REFERENCES SUCURSAL(id_sucursal),
    CONSTRAINT FK_MANTENCION_MECANICO FOREIGN KEY (cod_mecanico)
        REFERENCES MECANICO(cod_mecanico),
    CONSTRAINT FK_MANTENCION_AUTOMOVIL FOREIGN KEY (patente)
        REFERENCES AUTOMOVIL(patente)
);

CREATE TABLE DETALLE_SERVICIO (
    mantencion_num NUMBER(4),
    cod_servicio NUMBER(3),
    descuento_serv NUMBER(4,3),
    cantidad NUMBER(3),
    CONSTRAINT PK_DETALLE_SERVICIO
        PRIMARY KEY (mantencion_num, cod_servicio),
    CONSTRAINT FK_DETALLE_MANTENCION
        FOREIGN KEY (mantencion_num)
        REFERENCES MANTENCION(num_mantencion),
    CONSTRAINT FK_DETALLE_SERVICIO
        FOREIGN KEY (cod_servicio)
        REFERENCES SERVICIO(id_servicio)
);

